"""Generate the trailer's shot files (tools/trailer/shots/*.txt).

Shots are described here with floor-relative heights: floor(level, x, z)
looks up the nearest surveyed floor height (AI paths and item spawn points
from build/trailer/aerial/survey<L>.log, see aerial.py), because Woodshop,
Orient, Aqua and Future have several floor levels. World units; up is -y.

Helpers write camera keys for the common moves (line, orbit, crane). Each
shot gets the frames its edit slot needs plus HANDLE frames for transitions.

Usage: tools/trailer/shotgen.py   (then tools/trailer/render_all.sh [--preview|--final])
"""

