_floor_cache = {}


def floor(level, x, z):
    """Nearest surveyed floor height (y) to (x, z)."""
    if level not in _floor_cache:
        pts = []
        for line in open(f"{AERIAL}/survey{level}.log", encoding="latin1"):
            p = line.split()
            if line.startswith("[survey] player"):
                pts.append((int(p[4]), int(p[5]), int(p[6])))
            elif line.startswith("[survey] item"):
                pts.append((int(p[3]), int(p[4]), int(p[5])))
        _floor_cache[level] = pts
    best = min(_floor_cache[level], key=lambda p: (p[0] - x) ** 2 + (p[2] - z) ** 2)
    return best[1]


_path_cache = {}


def open_spot(level, x, z, lookahead=8):
    """Nearest surveyed AI path point to (x, z) and the unit travel direction
    there. AI players run through open aisles, so a camera placed along that
    direction has a clear line of sight. Returns ((x, y, z), (dx, dz))."""
    if level not in _path_cache:
        paths = {}
        for line in open(f"{AERIAL}/survey{level}.log", encoding="latin1"):
            if line.startswith("[survey] player"):
                p = line.split()
                paths.setdefault(int(p[3]), []).append((int(p[4]), int(p[5]), int(p[6])))
        _path_cache[level] = [v for v in paths.values() if len(v) > lookahead + 1]
    best = None
    for path in _path_cache[level]:
        for i in range(len(path) - lookahead):
            px, py, pz = path[i]
            qx, _, qz = path[i + lookahead]
            moved = math.hypot(qx - px, qz - pz)
            if moved < 300:                      # standing still: no direction
                continue
            d = (px - x) ** 2 + (pz - z) ** 2
            if best is None or d < best[0]:
                best = (d, (px, py, pz), ((qx - px) / moved, (qz - pz) / moved))
    return best[1], best[2]


def along(spot, direction, dist, height, side=0.0):
    """A point dist along the travel direction from spot (negative = behind),
    height above its floor, side to the right."""
    (x, y, z), (dx, dz) = spot, direction
    return (x + dx * dist + dz * side, y - height, z + dz * dist - dx * side)


def yaw_of(dx, dz):
    return math.degrees(math.atan2(dx, dz)) % 360


def key(t, pos, aim, fov=70.0):
    return (f"key {t:6.2f}  {pos[0]:7.0f} {pos[1]:7.0f} {pos[2]:7.0f}   "
            f"{aim[0]:7.0f} {aim[1]:7.0f} {aim[2]:7.0f}   {fov:.1f}")


def orbit(center, r0, r1, h0, h1, a0, a1, dur, aim_h, n=6, fov=70.0, t0=0.0):
    """Keys circling center (x, floor_y, z): radius r0->r1, height above
    floor h0->h1, angle a0->a1 degrees (0 = +z), aim at aim_h above floor."""
    cx, fy, cz = center
    out = []
    for i in range(n):
        u = i / (n - 1)
        a = math.radians(a0 + (a1 - a0) * u)
        r, h = r0 + (r1 - r0) * u, h0 + (h1 - h0) * u
        out.append(key(t0 + dur * u, (cx + math.sin(a) * r, fy - h, cz + math.cos(a) * r),
                       (cx, fy - aim_h, cz), fov))
    return out


def line(p0, p1, aim0, aim1, dur, fov=70.0, n=2, t0=0.0):
    out = []
    for i in range(n):
        u = i / (n - 1)
        lerp = lambda a, b: [a[k] + (b[k] - a[k]) * u for k in range(3)]
        out.append(key(t0 + dur * u, lerp(p0, p1), lerp(aim0, aim1), fov))
    return out


def hide_all(n):
    return [f"actor {i} hide" for i in range(n)] + [f"cart {i} hide" for i in range(n)]


def shot(name, level, frames, keys=(), extra=(), players=None, start=8.0, mode=None,
         world_speed=None, cast=None, comment="", zones_all=False, legacy=False, size=None):
    lines = [f"# {comment}" if comment else "# generated by tools/trailer/shotgen.py",
             f"shot        {name}", f"level       {level}"]
    if mode:
        lines.append(f"mode        {mode}")
    if players:
        lines.append(f"players     {players}")
    if cast:
        lines.append("cast        " + " ".join(str(c) for c in cast))
    lines += [f"start       {start}", f"frames      {frames}"]
    if size:
        lines.append(f"size        {size[0]} {size[1]}")
    if legacy:
        # The 1999 look: no motion blur and half the frame rate (12.5 fps).
        lines += ["env         MANIAC_LEGACY_LOOK 1", "blur        1", "hold        2"]
    if world_speed is not None:
        lines.append(f"world_speed {world_speed}")
    if zones_all:
        lines.append("zones       all")
    lines += list(extra) + list(keys)
    with open(os.path.join(SHOTS, name + ".txt"), "w") as f:
        f.write("\n".join(lines) + "\n")
    return name


def secs(frames):
    return frames / 25.0


